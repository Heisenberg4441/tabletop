#!/usr/bin/env python3
"""
build-strings.py — writes Resources/ru.lproj from the translation tables here.

The tables are JSON because they are easy to diff and to merge; the bundle
wants the old .strings/.stringsdict formats, so this turns one into the other
and, more importantly, checks coverage: every key the source asks for must be
translated, or the Russian app quietly shows English in that one place.

  ru-*.json          key -> translation
  ru-plurals.json    key -> [one, few, many]   (the key is the English "other"
                     form handed to Plural.format; Russian needs three forms,
                     which only a .stringsdict can choose between)

Usage: Tools/l10n/build-strings.py            (from the repository root)
Exit status 1 if a key is missing a translation.
"""
import glob, json, os, plistlib, subprocess, sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
here = os.path.join(root, 'Tools', 'l10n')
out = os.path.join(root, 'Resources', 'ru.lproj')
os.makedirs(out, exist_ok=True)

table = {}
for path in sorted(glob.glob(os.path.join(here, 'ru-*.json'))):
    if path.endswith('ru-plurals.json'):
        continue
    table.update(json.load(open(path, encoding='utf-8')))
plurals = json.load(open(os.path.join(here, 'ru-plurals.json'), encoding='utf-8'))

def quote(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'

with open(os.path.join(out, 'Localizable.strings'), 'w', encoding='utf-8') as f:
    f.write('/* Generated by Tools/l10n/build-strings.py — edit the JSON tables, not this file. */\n\n')
    for key in sorted(table):
        f.write(f'{quote(key)} = {quote(table[key])};\n')

dict_ = {}
for key, (one, few, many) in plurals.items():
    dict_[key] = {
        'NSStringLocalizedFormatKey': '%#@count@',
        'count': {
            'NSStringFormatSpecTypeKey': 'NSStringPluralRuleType',
            'NSStringFormatValueTypeKey': 'd',
            'one': one, 'few': few, 'many': many, 'other': few,
        },
    }
with open(os.path.join(out, 'Localizable.stringsdict'), 'wb') as f:
    plistlib.dump(dict_, f)

# An empty English table, so English is a localisation the bundle declares
# rather than merely the fallback it lands on.
en = os.path.join(root, 'Resources', 'en.lproj')
os.makedirs(en, exist_ok=True)
open(os.path.join(en, 'Localizable.strings'), 'w').write('/* English is the source language: keys are the text. */\n')

keys = json.loads(subprocess.check_output([os.path.join(root, 'Tools', 'extract-strings.py'), os.path.join(root, 'Sources')]))
missing = [k for k in keys if k not in table and k not in plurals]
unused = [k for k in list(table) + list(plurals) if k not in keys]
print(f'{len(table)} strings, {len(plurals)} plurals; {len(keys)} keys in the source')
if unused:
    print(f'{len(unused)} translations no longer used (harmless)')
if missing:
    print(f'{len(missing)} MISSING:')
    for k in missing:
        print('  ' + json.dumps(k, ensure_ascii=False) + '   // ' + keys[k][:70])
    sys.exit(1)
